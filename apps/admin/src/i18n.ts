type Dictionary = { [K in TranslationKey]: (typeof en)[K] };
const dictionaries: Record<Lang, Dictionary> = { en, zh };

/**
 * Translate a key. Function-valued keys (like envelopePosted) accept their
 * parameters as extra arguments.
 */
export type Translate = {
  <K extends TranslationKey>(key: K, ...args: (typeof en)[K] extends (...args: infer P) => unknown ? P : []): string;
};

export function useT() {
  const lang = useLang((state) => state.lang);
  const translate = (key: TranslationKey, ...args: unknown[]): string => {
    const entry = (dictionaries[lang][key] ?? dictionaries.en[key]) as unknown;
    return typeof entry === 'function' ? String((entry as (...f: unknown[]) => string)(...args)) : String(entry);
  };
  return translate as Translate;
}

