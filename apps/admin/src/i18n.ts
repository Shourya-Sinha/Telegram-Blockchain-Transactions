import { create } from 'zustand';

/**
 * Admin console language: English (en 🇬🇧) and Simplified Chinese (zh 🇨🇳).
 * Operator-only preference, persisted in localStorage.
 */
export type Lang = 'en' | 'zh';

export const LANGUAGES: Array<{ code: Lang; flag: string; codeLabel: string; name: string }> = [
  { code: 'en', flag: '🇬🇧', codeLabel: 'EN', name: 'English' },
  { code: 'zh', flag: '🇨🇳', codeLabel: 'ZH', name: '中文' }
];

const STORAGE_KEY = 'admin-lang';

function detectLanguage(): Lang {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'en' || stored === 'zh') return stored;
    if (navigator.language?.toLowerCase().startsWith('zh')) return 'zh';
  } catch { /* ignore */ }
  return 'en';
}

interface LangState {
  lang: Lang;
  setLang: (lang: Lang) => void;
}

export const useLang = create<LangState>((set) => ({
  lang: detectLanguage(),
  setLang: (lang) => {
    try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* ignore */ }
    set({ lang });
  }
}));

